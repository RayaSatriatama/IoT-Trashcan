import { afterEach, expect, it, vi } from 'vitest';
const state = vi.hoisted(() => ({ open: false, pressedOpen: null as boolean | null }));
vi.mock('react', async original => ({ ...await original<any>(), useState: () => [state.open, (value: boolean) => { state.open = value; }], useRef: () => ({ get current() { return state.pressedOpen; }, set current(value) { state.pressedOpen = value; } }) }));
vi.mock('../../lib/ui/motionContext', () => ({ useReducedMotion: () => false }));
vi.mock('tamagui', () => ({ Button: 'button', Text: 'span', XStack: 'div', Tooltip: Object.assign('tooltip', { Trigger: 'trigger', Content: 'content' }) }));
import { DescriptionHint } from '../../components/SectionHeader';
afterEach(() => { state.open = false; state.pressedOpen = null; });
it('opens explanatory info on tap and allows Escape dismissal without moving focus', () => {
  const tree = DescriptionHint({ description: 'TEST help', ariaLabel: 'Info TEST' });
  expect(tree.props.open).toBe(false);
  expect(tree.props.focus).toEqual({ enabled: true, visibleOnly: false });
  const contentProps = tree.props.children[1].props;
  expect(contentProps).not.toHaveProperty('elevate');
  expect(contentProps).not.toHaveProperty('bordered');
  expect(contentProps.borderWidth).toBe(1);
  expect(contentProps.shadowRadius).toBe(10);
  expect(contentProps.shadowOffset).toEqual({ height: 5, width: 0 });
  expect(contentProps.elevationAndroid).toBe(10);
  const trigger = tree.props.children[0].props.children;
  expect(trigger.props.minHeight).toBeGreaterThanOrEqual(44);
  expect(trigger.props.onPress).toBeTypeOf('function');
  trigger.props.onPress();
  const opened = DescriptionHint({ description: 'TEST help' });
  expect(opened.props.open).toBe(true);
  opened.props.children[0].props.children.props.onPress();
  expect(DescriptionHint({ description: 'TEST help' }).props.open).toBe(false);
  state.open = true;
  DescriptionHint({ description: 'TEST help' }).props.children[1].props.onEscapeKeyDown();
  expect(DescriptionHint({ description: 'TEST help' }).props.open).toBe(false);
});
it('opens for keyboard focus and preserves tap toggling when focus happens before press', () => {
  const button = () => DescriptionHint({ description: 'TEST help' }).props.children[0].props.children;
  expect(button().props.onFocus).toBeTypeOf('function');
  button().props.onFocus();
  expect(state.open).toBe(true);
  button().props.onBlur();
  expect(state.open).toBe(false);
  button().props.onPressIn();
  button().props.onFocus();
  button().props.onPress();
  expect(state.open).toBe(true);
  button().props.onPressIn();
  button().props.onPress();
  expect(state.open).toBe(false);
});
it('keeps the hint open when touch focus precedes press-in', () => {
  const button = () => DescriptionHint({ description: 'TEST help' }).props.children[0].props.children;
  button().props.onFocus();
  button().props.onPressIn();
  button().props.onPress();
  expect(state.open).toBe(true);
});
